using System.Buffers.Binary;
using System.Diagnostics;
using System.IO.Compression;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Windows.Media;
using System.Windows.Media.Imaging;
using ChappyStorageCompressor.Core;

// R2.17 part 2: a disposable, generated, *decodable* JPG/PNG profile.
// This intentionally does NOT launch any external JPEG program. The normal
// JPEG candidate engine requires a separately chosen trusted jpegtran.exe.
internal static class R217ValidImageBatchProfile
{
    private const int CountPerFormat = 12;
    private static readonly byte[] PngSignature =
        { 137, 80, 78, 71, 13, 10, 26, 10 };

    private sealed record Sample<T>(T Value, double ElapsedMs, long ThreadAllocatedBytes);

    private static Sample<T> Measure<T>(Func<T> action)
    {
        long before = GC.GetAllocatedBytesForCurrentThread();
        var clock = Stopwatch.StartNew();
        T result = action();
        clock.Stop();
        return new(result, clock.Elapsed.TotalMilliseconds,
            GC.GetAllocatedBytesForCurrentThread() - before);
    }

    private sealed class InlineProgress : IProgress<PngBatchPreviewEngine.Progress>
    {
        public int Updates { get; private set; }
        public int Completed { get; private set; }
        public int Failed { get; private set; }
        public void Report(PngBatchPreviewEngine.Progress update)
        {
            Updates++;
            if (update.Status == "Completed") Completed++;
            if (update.Status == "Failed") Failed++;
        }
    }

    private static byte[] Pixels(int width, int height, int index, bool noisy)
    {
        var pixels = new byte[checked(width * height * 4)];
        if (noisy) new Random(217500 + index).NextBytes(pixels);
        for (int y = 0; y < height; y++)
            for (int x = 0; x < width; x++)
            {
                int p = (y * width + x) * 4;
                if (!noisy)
                {
                    pixels[p] = (byte)(((x / 16) * 17 + index * 13) & 255); // B
                    pixels[p + 1] = (byte)(((y / 16) * 17 + index * 11) & 255); // G
                    pixels[p + 2] = (byte)((((x + y) / 24) * 7 + index * 19) & 255); // R
                }
                pixels[p + 3] = 255;
            }
        return pixels;
    }

    private static void WriteChunk(Stream output, string name, ReadOnlySpan<byte> payload)
    {
        Span<byte> header = stackalloc byte[8];
        BinaryPrimitives.WriteUInt32BigEndian(header[..4], (uint)payload.Length);
        Encoding.ASCII.GetBytes(name, header[4..8]);
        output.Write(header);
        output.Write(payload);
        uint crc = 0xFFFFFFFF;
        foreach (byte v in header[4..8])
        {
            crc ^= v;
            for (int bit = 0; bit < 8; bit++)
                crc = (crc & 1) == 1 ? (crc >> 1) ^ 0xEDB88320u : crc >> 1;
        }
        foreach (byte v in payload)
        {
            crc ^= v;
            for (int bit = 0; bit < 8; bit++)
                crc = (crc & 1) == 1 ? (crc >> 1) ^ 0xEDB88320u : crc >> 1;
        }
        Span<byte> trailer = stackalloc byte[4];
        BinaryPrimitives.WriteUInt32BigEndian(trailer, ~crc);
        output.Write(trailer);
    }

    private static void WriteValidPng(string path, int width, int height, byte[] bgra)
    {
        byte[] ihdr = new byte[13];
        BinaryPrimitives.WriteUInt32BigEndian(ihdr.AsSpan(0, 4), (uint)width);
        BinaryPrimitives.WriteUInt32BigEndian(ihdr.AsSpan(4, 4), (uint)height);
        ihdr[8] = 8; // 8-bit RGBA, filter=0, non-interlaced.
        ihdr[9] = 6;
        using var inflated = new MemoryStream();
        for (int y = 0; y < height; y++)
        {
            inflated.WriteByte(0); // None filter
            for (int x = 0; x < width; x++)
            {
                int p = (y * width + x) * 4;
                inflated.WriteByte(bgra[p + 2]);
                inflated.WriteByte(bgra[p + 1]);
                inflated.WriteByte(bgra[p]);
                inflated.WriteByte(bgra[p + 3]);
            }
        }
        using var zlibOutput = new MemoryStream();
        using (var zlib = new ZLibStream(zlibOutput, CompressionLevel.NoCompression, leaveOpen: true))
            inflated.WriteTo(zlib);
        using var output = File.Create(path);
        output.Write(PngSignature);
        WriteChunk(output, "IHDR", ihdr);
        WriteChunk(output, "tEXt", "Comment\0Generated by R2.17 test"u8);
        WriteChunk(output, "IDAT", zlibOutput.ToArray());
        WriteChunk(output, "IEND", ReadOnlySpan<byte>.Empty);
    }

    private static void WriteValidJpeg(string path, int width, int height, byte[] bgra)
    {
        var bitmap = BitmapSource.Create(width, height, 96, 96,
            PixelFormats.Bgra32, null, bgra, checked(width * 4));
        bitmap.Freeze();
        var encoder = new JpegBitmapEncoder { QualityLevel = 86 };
        encoder.Frames.Add(BitmapFrame.Create(bitmap));
        using var output = File.Create(path);
        encoder.Save(output);
    }

    private static string IndependentSha256(string file)
    {
        using var stream = File.OpenRead(file);
        return Convert.ToHexString(SHA256.HashData(stream));
    }

    private static (int Width, int Height, byte[] Bytes) DecodeBgra(string file)
    {
        using var stream = new FileStream(file, FileMode.Open, FileAccess.Read, FileShare.Read);
        var frames = BitmapDecoder.Create(stream, BitmapCreateOptions.PreservePixelFormat,
            BitmapCacheOption.OnLoad).Frames;
        if (frames.Count != 1) throw new InvalidDataException("Unexpected frame count");
        var converted = new FormatConvertedBitmap(frames[0], PixelFormats.Bgra32, null, 0);
        int width = converted.PixelWidth, height = converted.PixelHeight;
        var decoded = new byte[checked(width * height * 4)];
        converted.CopyPixels(decoded, checked(width * 4), 0);
        return (width, height, decoded);
    }

    public static void Run(string parent, Action<bool, string> check)
    {
        string root = Path.Combine(parent, "r217-valid-image-only");
        string input = Path.Combine(root, "generated-input");
        string output = Path.Combine(root, "separate-output");
        Directory.CreateDirectory(input);
        Directory.CreateDirectory(output);

        try
        {
            var generated = Measure(() =>
            {
                for (int i = 0; i < CountPerFormat; i++)
                {
                    bool noisy = i % 2 == 1;
                    byte[] png = Pixels(384, 256, i, noisy);
                    WriteValidPng(Path.Combine(input, $"synthetic-{i:D2}.png"),
                        384, 256, png);
                    byte[] jpeg = Pixels(640, 480, i + 100, noisy);
                    WriteValidJpeg(Path.Combine(input, $"synthetic-{i:D2}.jpg"),
                        640, 480, jpeg);
                }
                return Directory.EnumerateFiles(input).Count();
            });
            check(generated.Value == CountPerFormat * 2,
                "R2.17: 12 PNG + 12 JPEG files generated without external inputs");

            var originals = Directory.EnumerateFiles(input).ToDictionary(
                x => Path.GetFileName(x), IndependentSha256,
                StringComparer.OrdinalIgnoreCase);
            long inputBytes = Directory.EnumerateFiles(input)
                .Sum(p => new FileInfo(p).Length);

            var preflight = Measure(() => PersonalMediaBatchPreflight.Inspect(input, output));
            check(preflight.Value.PngFiles == CountPerFormat &&
                  preflight.Value.JpegFiles == CountPerFormat &&
                  preflight.Value.ScanErrors == 0 &&
                  preflight.Value.ActualFreedBytes == 0,
                "R2.17: combined preflight counts valid synthetic media without mutation");

            var jpegPlan = Measure(() => JpegBatchPreviewEngine.BuildPlan(input, output,
                Path.Combine(root, "jpegtran.exe"), CancellationToken.None));
            check(jpegPlan.Value.Entries.Count == CountPerFormat &&
                  jpegPlan.Value.Entries.All(e => e.RelativePath.EndsWith(".jpg",
                      StringComparison.OrdinalIgnoreCase)),
                "R2.17: JPEG batch planning uses actual valid generated JPEGs");

            var jpegAudit = Measure(() =>
            {
                int decoded = 0;
                foreach (string path in Directory.EnumerateFiles(input, "*.jpg"))
                {
                    var marker = JpegMarkerAudit.Inspect(path);
                    var image = DecodeBgra(path);
                    if (marker.Width != 640 || marker.Height != 480 ||
                        image.Width != 640 || image.Height != 480)
                        throw new InvalidDataException("Generated JPEG validation mismatch");
                    decoded++;
                }
                return decoded;
            });
            check(jpegAudit.Value == CountPerFormat,
                "R2.17: 12 genuine JPEGs pass marker verification and WIC full decode");

            var pngSourceDecode = Measure(() =>
            {
                int decoded = 0;
                foreach (string path in Directory.EnumerateFiles(input, "*.png"))
                {
                    var header = PngInspector.Inspect(path);
                    var image = DecodeBgra(path);
                    if (header.Width != 384 || header.Height != 256 ||
                        image.Width != 384 || image.Height != 256)
                        throw new InvalidDataException("Generated PNG validation mismatch");
                    decoded++;
                }
                return decoded;
            });
            check(pngSourceDecode.Value == CountPerFormat,
                "R2.17: 12 genuine PNGs pass CRC/chunk checks and WIC full decode");

            var progress = new InlineProgress();
            var pngFirst = Measure(() => PngBatchPreviewEngine.Run(input, output, progress));
            check(pngFirst.Value.Total == CountPerFormat &&
                  pngFirst.Value.Failed == 0 &&
                  pngFirst.Value.Optimized > 0 &&
                  pngFirst.Value.SavedBytes > 0 &&
                  progress.Updates >= CountPerFormat,
                "R2.17: production PNG preview batch processes valid data and saves only candidates");

            string previewFolder = Path.Combine(output, "chappy-png-previews");
            var pixelAudit = Measure(() =>
            {
                int checkedPreviews = 0;
                foreach (string preview in Directory.EnumerateFiles(previewFolder, "*.png"))
                {
                    string name = Path.GetFileName(preview);
                    int marker = name.IndexOf(".chappy-preview-", StringComparison.Ordinal);
                    if (marker < 0) throw new InvalidDataException("Unexpected preview name");
                    string original = Path.Combine(input, name[..marker] + ".png");
                    var source = DecodeBgra(original);
                    var candidate = DecodeBgra(preview);
                    if (source.Width != candidate.Width ||
                        source.Height != candidate.Height ||
                        !source.Bytes.AsSpan().SequenceEqual(candidate.Bytes))
                        throw new InvalidDataException("Preview decoded pixels changed");
                    checkedPreviews++;
                }
                return checkedPreviews;
            });
            check(pixelAudit.Value == pngFirst.Value.Optimized,
                "R2.17: independent WIC comparison proves saved PNG candidates preserve pixels");

            var pngResume = Measure(() => PngBatchPreviewEngine.Run(input, output));
            check(pngResume.Value.Optimized == pngFirst.Value.Optimized &&
                  pngResume.Value.Failed == 0 &&
                  Directory.EnumerateFiles(previewFolder, "*.png").Count() ==
                      pngFirst.Value.Optimized,
                "R2.17: repeat batch reuses valid previews without generating more copies");

            var after = Directory.EnumerateFiles(input).ToDictionary(
                x => Path.GetFileName(x), IndependentSha256,
                StringComparer.OrdinalIgnoreCase);
            check(originals.Count == after.Count && originals.All(x =>
                      after.TryGetValue(x.Key, out var h) && h == x.Value),
                "R2.17: full PNG/JPEG fixture SHA-256 unchanged after planning and preview");
            check(preflight.Value.TotalFiles == CountPerFormat * 2 &&
                  pngFirst.Value.SavedBytes > 0 &&
                  pngResume.Value.SavedBytes == pngFirst.Value.SavedBytes,
                "R2.17: combined preview remains an estimate; no originals replaced");

            var phases = new[] {
                ("generate", generated.ElapsedMs),
                ("combinedPreflight", preflight.ElapsedMs),
                ("jpegPlan", jpegPlan.ElapsedMs),
                ("jpegMarkerPlusWicDecode", jpegAudit.ElapsedMs),
                ("pngSourceDecode", pngSourceDecode.ElapsedMs),
                ("pngBatchFirst", pngFirst.ElapsedMs),
                ("pngCandidateIndependentPixelAudit", pixelAudit.ElapsedMs),
                ("pngBatchResume", pngResume.ElapsedMs)
            };
            string slowest = phases.OrderByDescending(x => x.Item2).First().Item1;

            Directory.CreateDirectory("diagnostics");
            File.WriteAllText(Path.Combine("diagnostics", "r217-valid-image-profile.json"),
                JsonSerializer.Serialize(new
                {
                    schema = "chappy-r217-valid-generated-media-v1",
                    fixture = "only synthetically generated WIC-decodable PNG/JPEG",
                    generatedValidPngCount = CountPerFormat,
                    generatedValidJpegCount = CountPerFormat,
                    generatedInputBytes = inputBytes,
                    pngPreviewCandidateCount = pngFirst.Value.Optimized,
                    pngVerifiedDecodedCandidates = pixelAudit.Value,
                    pngTheoreticalSavedBytes = pngFirst.Value.SavedBytes,
                    pngBatchFailureCount = pngFirst.Value.Failed,
                    jpegMarkerWicValidatedCount = jpegAudit.Value,
                    jpegCandidateOptimizationMeasured = false,
                    jpegExternalExecutableInvoked = false,
                    jpegEngineMeasuredOnlyForPlanning = true,
                    progressUpdateCount = progress.Updates,
                    generationElapsedMs = generated.ElapsedMs,
                    preflightElapsedMs = preflight.ElapsedMs,
                    jpegPlanElapsedMs = jpegPlan.ElapsedMs,
                    jpegDecodeAndAuditElapsedMs = jpegAudit.ElapsedMs,
                    pngDecodeElapsedMs = pngSourceDecode.ElapsedMs,
                    pngBatchFirstElapsedMs = pngFirst.ElapsedMs,
                    pngIndependentPixelAuditElapsedMs = pixelAudit.ElapsedMs,
                    pngResumeElapsedMs = pngResume.ElapsedMs,
                    biggestMeasuredPhaseByElapsedMs = slowest,
                    pngBatchThreadAllocationBytes = pngFirst.ThreadAllocatedBytes,
                    jpegDecodeAndAuditThreadAllocationBytes = jpegAudit.ThreadAllocatedBytes,
                    hardwareDiskReadsMeasured = false,
                    guiWorkflowVerified = false,
                    timingSpeedupClaimed = false,
                    productionOriginalReplacementEnabled = false,
                    productionHardlinkMergeEnabled = false,
                    actualFreedBytes = 0,
                    originalMediaTouched = false,
                    verdict = "PASS"
                }, new JsonSerializerOptions { WriteIndented = true }));

            Console.WriteLine($"R2.17 valid image profile: {CountPerFormat} PNG + " +
                $"{CountPerFormat} JPEG; PNG first {pngFirst.ElapsedMs:F1} ms, " +
                $"resume {pngResume.ElapsedMs:F1} ms; JPEG external optimizer NOT RUN");
        }
        finally
        {
            Directory.Delete(root, recursive: true);
        }
    }
}
